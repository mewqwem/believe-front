export const dictionaries: Record<Locale, Record<string, string>> = { uk, pl, en };

export function normalizeLocale(value: unknown): Locale {
  return locales.includes(value as Locale) ? (value as Locale) : "uk";
}

export function translate(locale: Locale, key: string, values: TranslationValues = {}) {
  const template = dictionaries[locale][key] ?? dictionaries.uk[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}
